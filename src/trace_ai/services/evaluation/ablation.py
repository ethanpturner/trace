"""The ablation table: what each removed component changed, rendered from the harness comparison.

The ablation set (`stability.run_ablation_set`) replays each scenario's recording with one component
removed at a time — evidence validation, critical review, context approval — against the
authoritative run. This renders those comparisons as one Markdown table per the portfolio narrative,
so the write-up references a committed artifact rather than hand-copying numbers that drift.

It inherits the scorecard's boundary (DEC-076): metrics and identifiers only, no finding text. Every
ablated row is non-authoritative by construction (DEC-012, DEC-031) and marked as such. A delta of
zero is shown, not hidden — a component whose removal moves no metric on these recordings is a
result the narrative has to report, not omit.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Sequence
    from datetime import datetime

    from trace_ai.services.evaluation.stability import AblationComparison

__all__ = ["METRICS", "AblationRow", "render_ablation", "rows_from_comparisons"]

# The metrics the table reports, in column order, with the label each carries. False-negative rate
# leads because it is the one the ablations move: removing evidence validation makes the pipeline
# miss the finding it otherwise reports.
METRICS: tuple[tuple[str, str], ...] = (
    ("false_negative_rate", "False-negative rate"),
    ("finding_evidence_coverage", "Evidence coverage"),
    ("false_positive_rate", "False-positive rate"),
    ("duplicate_finding_rate", "Duplicate rate"),
)

# How each removed component is labelled in the table, in report order.
_COMPONENT_LABELS = {
    "no-evidence-validation": "no evidence validation",
    "no-critical-review": "no critical review",
    "no-context-approval": "no context approval",
}


@dataclass(frozen=True, slots=True)
class AblationRow:
    """One run line: the authoritative pipeline, or it with one component removed."""

    scenario: str
    component: str
    authoritative: bool
    metrics: dict[str, float]
    deltas: dict[str, float | None]


def rows_from_comparisons(comparisons: Sequence[AblationComparison]) -> list[AblationRow]:
    """One authoritative row per scenario, then one row per removed component, sorted."""
    rows: list[AblationRow] = []
    for comparison in sorted(comparisons, key=lambda comparison: comparison.scenario):
        rows.append(
            AblationRow(
                scenario=comparison.scenario,
                component="authoritative",
                authoritative=True,
                metrics=dict(comparison.authoritative),
                deltas={},
            )
        )
        for component in _COMPONENT_LABELS:
            if component not in comparison.ablations:
                continue
            rows.append(
                AblationRow(
                    scenario=comparison.scenario,
                    component=component,
                    authoritative=False,
                    metrics=dict(comparison.ablations[component]),
                    deltas={name: comparison.delta(component, name) for name, _ in METRICS},
                )
            )
    return rows


def _pct(value: float | None) -> str:
    return "—" if value is None else f"{value * 100:.0f}%"


def _delta(value: float | None) -> str:
    if value is None or value == 0:
        return ""
    return f" ({value * 100:+.0f})"


def _cell(row: AblationRow, metric: str) -> str:
    value = row.metrics.get(metric)
    if value is None:
        return "—"
    return f"{_pct(value)}{_delta(row.deltas.get(metric))}"


def render_ablation(
    comparisons: Sequence[AblationComparison],
    *,
    generated_at: datetime,
    pins: dict[str, str],
) -> str:
    """Render the ablation comparisons as Markdown. Metrics and identifiers only (DEC-076)."""
    rows = rows_from_comparisons(comparisons)
    labels = [label for _, label in METRICS]
    header = "| Scenario | Run | " + " | ".join(labels) + " |"
    divider = "| --- | --- | " + " | ".join("---" for _ in labels) + " |"

    body: list[str] = []
    previous: str | None = None
    for row in rows:
        scenario = row.scenario if row.scenario != previous else ""
        previous = row.scenario
        run = "authoritative" if row.authoritative else f"{_COMPONENT_LABELS[row.component]} *"
        cells = " | ".join(_cell(row, name) for name, _ in METRICS)
        body.append(f"| {scenario} | {run} | {cells} |")

    scenarios = len({comparison.scenario for comparison in comparisons})
    pin_text = ", ".join(f"{key} {value}" for key, value in pins.items())

    return f"""<!-- Generated by scripts/build_ablation.py — do not edit by hand. -->
# Ablation: what each removed component changes

Each scenario's recording replayed with one component removed at a time, against the authoritative
run. Regenerated offline from the recorded runs by `scripts/build_ablation.py`; a parenthesised
number is the change from the authoritative run in points, and a blank means the metric did not
move. Rows marked `*` are non-authoritative (DEC-012). Metrics and identifiers only — no assessment
content (DEC-076). Generated {generated_at.date().isoformat()} over {scenarios} scenarios ({pin_text}).

{header}
{divider}
{chr(10).join(body)}

Lower is better for every column except evidence coverage. **Read the dashes before the numbers.**
Removing evidence validation leaves every mapping unassessed, and DEC-013 resolves an unassessed
mapping to no output — so those runs produce no findings at all, and every rate denominated on the
finding set is unmeasured rather than improved (DEC-150). The ablation therefore shows that the
component is structurally required, not that it improves the findings it is removed from: what it
costs is visible only in the false-negative column, where parcel-platform rises 50 points and
reply-tuner 100.

Critical review moves no metric in any scenario — a null result stated rather than omitted.
Context approval moves one: reply-tuner's false-negative rate rises 100 points without it. Both
readings are bounded by a deterministic offline corpus of fifteen scenarios and are not a claim
that either component is idle elsewhere.
"""
